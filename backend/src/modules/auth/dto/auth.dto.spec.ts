import { loginSchema } from './auth.dto';

/**
 * Телефон — естественный ключ входа, и пишут его как придётся.
 * Если нормализация разъедется, один и тот же человек заведёт себе
 * второй аккаунт, а привязка Telegram перестанет находить сотрудника.
 */
describe('нормализация телефона', () => {
  const normalize = (phone: string) => loginSchema.parse({ phone, password: 'luna12345' }).phone;

  it.each([
    ['+998901234567', '+998901234567'],
    ['998901234567', '+998901234567'],
    ['901234567', '+998901234567'],
    ['+998 90 123-45-67', '+998901234567'],
    ['(90) 123 45 67', '+998901234567'],
    ['+998 (90) 123-45-67', '+998901234567'],
  ])('%s → %s', (input, expected) => {
    expect(normalize(input)).toBe(expected);
  });

  it.each([
    ['12345', 'слишком коротко'],
    ['+9989012345678', 'лишняя цифра'],
    ['+79161234567', 'чужой код страны'],
    ['+998abcdefghi', 'буквы вместо цифр'],
    ['', 'пусто'],
  ])('отклоняет %s (%s)', (input) => {
    expect(() => normalize(input)).toThrow();
  });
});
