import { SetMetadata } from '@nestjs/common';

export const IDEMPOTENT_KEY = 'idempotent';

/**
 * Помечает операцию, повтор которой недопустим.
 *
 * Ставится на всё, что создаёт деньги или движение склада. Сеть в цехе
 * отваливается на середине запроса: пользователь видит ошибку, жмёт
 * «Сохранить» ещё раз, а первый запрос на сервере уже прошёл. Без защиты
 * в кассе окажутся две одинаковые продажи, и найти это можно будет только
 * при инвентаризации.
 *
 * Заголовок `Idempotency-Key` при этом необязателен: клиент, который его
 * не шлёт, работает как раньше. Требовать его — значит сломать всех
 * существующих клиентов ради защиты, которой они не просили.
 */
export const Idempotent = () => SetMetadata(IDEMPOTENT_KEY, true);
