import 'package:dio/dio.dart';
import 'package:uuid/uuid.dart';

/// Ключ идемпотентности для денежной операции.
///
/// Сеть в цехе отваливается на середине запроса: человек видит ошибку и
/// жмёт «Сохранить» ещё раз, а первый запрос на сервере уже прошёл.
/// Бэкенд по этому ключу вернёт первый результат вместо второй выплаты.
///
/// Ключ живёт на попытку, а не на запрос: повтор после ошибки сети обязан
/// уйти с ТЕМ ЖЕ ключом, иначе защита бессмысленна. Поэтому он создаётся
/// на экране один раз и переиспользуется, пока пользователь не изменит
/// данные формы.
class IdempotencyKey {
  IdempotencyKey() : value = const Uuid().v4();

  final String value;

  Options get options => Options(headers: {'Idempotency-Key': value});
}
